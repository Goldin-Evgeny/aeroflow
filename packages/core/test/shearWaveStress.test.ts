  it('applies the predeclared discrimination rules without changing their limits', () => {
    const m1 = get('M1');
    const m2 = get('M2');
    const m3 = get('M3');
    const m4 = get('M4');
    const m5 = get('M5');
    const m6 = get('M6');
    const w8 = get('W8');
    const w24 = get('W24');
    const p16 = get('P16');
    const plain = get('PLAIN');
    const clean = get('CLEAN');
    const g2 = get('G2');
    const g3 = get('G3');
    const plain08 = get('PLAIN08');
    const slope = (result: CaseResult): number => result.finiteDifference.throughOriginSlope;
    const normalizedM2 = slope(m2) / slope(m1);
    const normalizedM3 = slope(m3) / slope(m1);
    const normalizedG2 = slope(g2) / slope(clean);
    const normalizedG3 = slope(g3) / slope(clean);
    const g2Change = 1 - normalizedG2;
    const g3Change = 1 - normalizedG3;
    const cubicGiDetected =
      Math.abs(normalizedG2 - 0.9925) <= 0.0025 &&
      Math.abs(normalizedG3 - 0.97) <= 0.0025 &&
      Math.abs(g3Change / g2Change - 4) <= 0.8 &&
      relativeDifference(slope(m4), slope(m2)) <= 0.005 &&
      relativeDifference(slope(m5), slope(m2)) <= 0.005 &&
      relativeDifference(slope(m6), slope(m1)) <= 0.005;
    const fixedIndexComponent =
      relativeDifference(slope(m4), slope(m2)) <= 0.005 &&
      relativeDifference(slope(m5), slope(m2)) > 0.02;
    const globalNormalization =
      [m1, m2, m4, m5, m6].every(
        (result) =>
          Math.abs(result.finiteDifference.phaseDegrees) <= 1 && Math.abs(slope(result) - 1) > 0.02,
      ) &&
      Math.max(slope(m1), slope(m2), slope(m4), slope(m5), slope(m6)) -
        Math.min(slope(m1), slope(m2), slope(m4), slope(m5), slope(m6)) <=
        0.02;
    const fdTransferMatch = [w8, w24].every((result) => {
      const expected = 1 / result.centeredDifferenceTransfer;
      return (
        Math.abs(
          result.finiteDifference.amplitude / result.analyticDerivative.amplitude - expected,
        ) /
          expected <=
        0.05
      );
    });
    const analyticHighKNearUnity = [w8, w24].every(
      (result) => Math.abs(result.analyticDerivative.amplitude - 1) <= 0.05,
    );
    const centeredFdError = fdTransferMatch && analyticHighKNearUnity;
    const finiteKnudsenAtHighK =
      fdTransferMatch &&
      w8.analyticDerivative.amplitude > 1.05 &&
      w24.analyticDerivative.amplitude > w8.analyticDerivative.amplitude;
    const fp16RelativeChange = relativeDifference(slope(p16), slope(m2));
    const fp16Material = fp16RelativeChange > 0.05;
    const projectionRelativeChange = relativeDifference(slope(plain08), slope(g2));
    const projectedRegularizationMaterial = projectionRelativeChange > 0.02;
    const smoothCasesPass =
      Math.abs(clean.analyticDerivative.amplitude - 1) <= 0.02 &&
      Math.abs(normalizedG2 - 0.9925) <= 0.02 &&
      Math.abs(normalizedG3 - 0.97) <= 0.02 &&
      relativeDifference(slope(m4), slope(m2)) <= 0.005 &&
      relativeDifference(slope(m5), slope(m2)) <= 0.005 &&
      relativeDifference(slope(m6), slope(m1)) <= 0.005;
    const finiteResolution =
      smoothCasesPass &&
      w24.finiteDifference.amplitude > w8.finiteDifference.amplitude &&
      w8.finiteDifference.amplitude > m1.finiteDifference.amplitude;
    const timeAlignmentCandidates = [
      { name: 'same-step', value: m2.finiteDifference },
      { name: 'previous-step', value: m2.previousStepFiniteDifference },
      { name: 'midpoint', value: m2.midpointFiniteDifference },
    ];
    const bestTimeAlignment = timeAlignmentCandidates.reduce((best, candidate) => {
      const score =
        Math.abs(candidate.value.phaseDegrees) + 10 * Math.abs(candidate.value.amplitude - 0.9925);
      const bestScore =
        Math.abs(best.value.phaseDegrees) + 10 * Math.abs(best.value.amplitude - 0.9925);
      return score < bestScore ? candidate : best;
    });
    const timeLevelError =
      bestTimeAlignment.name !== 'same-step' &&
      Math.abs(bestTimeAlignment.value.phaseDegrees) <= 1 &&
      Math.abs(bestTimeAlignment.value.amplitude - 0.9925) <= 0.02;

    let classification = 'mixed / unresolved';
    if (finiteResolution && finiteKnudsenAtHighK) {
      classification = 'finite-resolution plus finite-Knudsen constitutive departure';
    } else if (centeredFdError && finiteResolution) {
      classification = 'finite-resolution / centered-FD transfer';
    } else if (fp16Material) {
      classification = 'FP16-correlated reconstruction contribution';
    } else if (fixedIndexComponent) {
      classification = 'fixed component/index implementation anisotropy';
    } else if (globalNormalization) {
      classification = 'global constitutive normalization mismatch';
    } else if (projectedRegularizationMaterial) {
      classification = 'projected-regularization-specific constitutive behavior';
    } else if (cubicGiDetected) {
      classification = 'small cubic/Galilean defect detected; insufficient for Ahmed';
    } else if (smoothCasesPass) {
      classification = 'Ahmed-specific finite-Knudsen / non-hydrodynamic state';
    }

    const discrimination: CalibrationArtifact['discrimination'] = {
      harnessPass: guards.cleanHarnessPass === true,
      normalizedM2,
      normalizedM3,
      normalizedG2,
      normalizedG3,
      expectedM2: 0.9925,
      expectedM3: 0.97,
      cubicGiDetected,
      cubicGiCanExplainAhmedFactor: false,
      fixedIndexComponent,
      globalNormalization,
      centeredFdError,
      finiteKnudsenAtHighK,
      fdTransferMatch,
      analyticHighKNearUnity,
      fp16RelativeChange,
      fp16Material,
      projectionRelativeChange,
      projectedRegularizationMaterial,
      exactAhmedPlainProjectionRelativeChange: relativeDifference(slope(plain), slope(m2)),
      smoothCasesPass,
      finiteResolution,
      bestTimeAlignment: bestTimeAlignment.name,
      bestTimeAlignmentPhaseDegrees: bestTimeAlignment.value.phaseDegrees,
      bestTimeAlignmentAmplitude: bestTimeAlignment.value.amplitude,
      timeLevelError,
    };
    artifact = {
      generatedAt: new Date().toISOString(),
      purpose:
        'Dynamic periodic D3Q19 calibration for the Ahmed approach-region Pi-vs-FD tensor mismatch',
      constants: {
        amplitude: AMPLITUDE,
        longAxis: LONG_AXIS,
        shortAxis: SHORT_AXIS,
        ahmedTau0: AHMED_TAU0,
        ahmedLesCs: AHMED_LES_CS,
        lambda: TRT_LAMBDA,
        cs2: CS2,
        mainSteps: MAIN_STEPS,
        mainDiscard: MAIN_DISCARD,
        artifactSchema: 'aeroflow-shear-wave-stress-v1',
      },
      guards,
      cases: Array.from(results.values()).map(withoutState),
      discrimination,
      classification,
    };

    expect(discrimination.harnessPass).toBe(true);
    expect(discrimination.cubicGiCanExplainAhmedFactor).toBe(false);
  });
