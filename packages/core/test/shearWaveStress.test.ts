/**
 * Dynamic, fully periodic D3Q19 calibration for the Ahmed Pi-vs-FD diagnosis.
 *
 * This is intentionally a test-local two-array pull solver. It shares the production
 * equilibrium, Pi reconstruction and collision functions, but has no walls, inlet, outlet,
 * body, GPU storage layout or application state. A sinusoidal transverse velocity is placed
 * in equilibrium populations at t=0; Pi_neq is therefore generated by streaming/collision,
 * never manufactured. The predeclared matrix and discrimination limits are documented in the
 * test names and in the emitted raw JSON artifact.
 */

