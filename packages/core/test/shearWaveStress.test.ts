function dimensions(axis: Axis): readonly [number, number, number] {
  if (axis === 0) return [LONG_AXIS, SHORT_AXIS, SHORT_AXIS];
  if (axis === 1) return [SHORT_AXIS, LONG_AXIS, SHORT_AXIS];
  return [SHORT_AXIS, SHORT_AXIS, LONG_AXIS];
}

function componentFor(
  waveAxis: Axis,
  polarization: Axis,
): {
  index: 3 | 4 | 5;
  name: 'xy' | 'xz' | 'yz';
} {
  const lo = Math.min(waveAxis, polarization);
  const hi = Math.max(waveAxis, polarization);
  if (lo === 0 && hi === 1) return { index: 3, name: 'xy' };
  if (lo === 0 && hi === 2) return { index: 4, name: 'xz' };
  if (lo === 1 && hi === 2) return { index: 5, name: 'yz' };
  throw new Error('transverse shear requires two different axes');
}

function coordinate(x: number, y: number, z: number, axis: Axis): number {
  return axis === 0 ? x : axis === 1 ? y : z;
}

function magnitude(z: Complex): number {
  return Math.hypot(z.re, z.im);
}

function divide(a: Complex, b: Complex): Complex {
  const denominator = b.re * b.re + b.im * b.im;
  return {
    re: (a.re * b.re + a.im * b.im) / denominator,
    im: (a.im * b.re - a.re * b.im) / denominator,
  };
}

function mean(values: readonly number[]): number {
  let sum = 0;
  for (const value of values) sum += value;
  return sum / values.length;
}

function meanRatio(values: readonly RatioMeasurement[]): RatioMeasurement {
  return {
    real: mean(values.map((value) => value.real)),
    imaginary: mean(values.map((value) => value.imaginary)),
    amplitude: mean(values.map((value) => value.amplitude)),
    phaseDegrees: mean(values.map((value) => value.phaseDegrees)),
    throughOriginSlope: mean(values.map((value) => value.throughOriginSlope)),
    pearson: mean(values.map((value) => value.pearson)),
  };
}

function linearStats(
  reference: Float64Array,
  actual: Float64Array,
): {
  slope: number;
  pearson: number;
} {
  let dot = 0;
  let reference2 = 0;
  let sumReference = 0;
  let sumActual = 0;
  for (let i = 0; i < reference.length; i++) {
    dot += reference[i] * actual[i];
    reference2 += reference[i] * reference[i];
    sumReference += reference[i];
    sumActual += actual[i];
  }
  const slope = dot / reference2;
  const meanReference = sumReference / reference.length;
  const meanActual = sumActual / actual.length;
  let covariance = 0;
  let varianceReference = 0;
  let varianceActual = 0;
  for (let i = 0; i < reference.length; i++) {
    const dx = reference[i] - meanReference;
    const dy = actual[i] - meanActual;
    covariance += dx * dy;
    varianceReference += dx * dx;
    varianceActual += dy * dy;
  }
  const pearson = covariance / Math.sqrt(varianceReference * varianceActual);
  return { slope, pearson: Math.max(-1, Math.min(1, pearson)) };
}

function fourier(values: Float64Array, coordinates: Int32Array, k: number): Complex {
  let re = 0;
  let im = 0;
  for (let i = 0; i < values.length; i++) {
    const angle = k * coordinates[i];
    re += values[i] * Math.cos(angle);
    im -= values[i] * Math.sin(angle);
  }
  return { re: re / values.length, im: im / values.length };
}

function ratioMeasurement(
  pi: Float64Array,
  hydro: Float64Array,
  coordinates: Int32Array,
  k: number,
): RatioMeasurement {
  const piHat = fourier(pi, coordinates, k);
  const hydroHat = fourier(hydro, coordinates, k);
  const ratio = divide(piHat, hydroHat);
  const stats = linearStats(hydro, pi);
  return {
    real: ratio.re,
    imaginary: ratio.im,
    amplitude: magnitude(ratio),
    phaseDegrees: (Math.atan2(ratio.im, ratio.re) * 180) / Math.PI,
    throughOriginSlope: stats.slope,
    pearson: stats.pearson,
  };
}

/** IEEE-754 binary32 to binary16, round-to-nearest-even. */
function floatToHalf(value: number): number {
  const f32 = new Float32Array(1);
  const u32 = new Uint32Array(f32.buffer);
  f32[0] = value;
  const bits = u32[0];
  const sign = (bits >>> 16) & 0x8000;
  let exponent = ((bits >>> 23) & 0xff) - 127 + 15;
  let mantissa = bits & 0x7fffff;
  if (exponent <= 0) {
    if (exponent < -10) return sign;
    mantissa = (mantissa | 0x800000) >>> (1 - exponent);
    const rounded = mantissa + 0xfff + ((mantissa >>> 13) & 1);
    return sign | (rounded >>> 13);
  }
  if (exponent >= 0x1f) {
    if (((bits >>> 23) & 0xff) === 0xff && mantissa !== 0) return sign | 0x7e00;
    return sign | 0x7c00;
  }
  mantissa += 0xfff + ((mantissa >>> 13) & 1);
  if ((mantissa & 0x800000) !== 0) {
    mantissa = 0;
    exponent++;
    if (exponent >= 0x1f) return sign | 0x7c00;
  }
  return sign | (exponent << 10) | (mantissa >>> 13);
}

/** Same exact half-bit interpretation used by the tau oracle's lookup table. */
function halfToFloat(half: number): number {
  const sign = (half & 0x8000) << 16;
  let exponent = (half >>> 10) & 0x1f;
  let mantissa = half & 0x3ff;
  let word: number;
  if (exponent === 0) {
    if (mantissa === 0) {
      word = sign;
    } else {
      exponent = 1;
      while ((mantissa & 0x400) === 0) {
        mantissa <<= 1;
        exponent--;
      }
      mantissa &= 0x3ff;
      word = sign | ((exponent + 127 - 15) << 23) | (mantissa << 13);
    }
  } else if (exponent === 0x1f) {
    word = sign | 0x7f800000 | (mantissa << 13);
  } else {
    word = sign | ((exponent + 127 - 15) << 23) | (mantissa << 13);
  }
  const bits = new Uint32Array(1);
  const value = new Float32Array(bits.buffer);
  bits[0] = word >>> 0;
  return value[0];
}

function shiftedFp16(value: number, direction: number): number {
  return halfToFloat(floatToHalf(Math.fround(value - D3Q19.w[direction]))) + D3Q19.w[direction];
}

class PeriodicShearWave {
  readonly nx: number;
  readonly ny: number;
  readonly nz: number;
  readonly n: number;
  readonly k: number;
  readonly target: ReturnType<typeof componentFor>;
  readonly coordinates: Int32Array;
  readonly ctx: CollideContext;
  readonly storage: Storage;
  readonly waveAxis: Axis;
  readonly polarization: Axis;
  private source: Float64Array;
  private destination: Float64Array;
  private readonly gathered = new Float64Array(D3Q19.q);
  private previousHydroFd: Float64Array | undefined;
  private stepNumber = 0;

  constructor(spec: WaveCase) {
    [this.nx, this.ny, this.nz] = dimensions(spec.waveAxis);
    this.n = this.nx * this.ny * this.nz;
    this.waveAxis = spec.waveAxis;
    this.polarization = spec.polarization;
    this.target = componentFor(spec.waveAxis, spec.polarization);
    this.storage = spec.storage ?? 'float64';
    const mode = spec.mode ?? 1;
    this.k = (2 * Math.PI * mode) / LONG_AXIS;
    this.coordinates = new Int32Array(this.n);
    this.source = new Float64Array(D3Q19.q * this.n);
    this.destination = new Float64Array(D3Q19.q * this.n);
    this.ctx = makeCollideContext(D3Q19_SPEC, {
      tau: spec.tau ?? AHMED_TAU0,
      collision: spec.collision ?? 'trt',
      lambda: TRT_LAMBDA,
      lesCs: spec.lesCs ?? AHMED_LES_CS,
      regularize: spec.regularize ?? true,
      conserveMass: spec.conserveMass ?? true,
    });

    for (let z = 0; z < this.nz; z++) {
      for (let y = 0; y < this.ny; y++) {
        for (let x = 0; x < this.nx; x++) {
          const idx = this.index(x, y, z);
          const coord = coordinate(x, y, z, spec.waveAxis);
          this.coordinates[idx] = coord;
          const velocity = [...spec.background];
          velocity[spec.polarization] += AMPLITUDE * Math.sin(this.k * coord);
          for (let direction = 0; direction < D3Q19.q; direction++) {
            const value = equilibrium3(
              D3Q19_SPEC,
              direction,
              1,
              velocity[0],
              velocity[1],
              velocity[2],
            );
            this.source[direction * this.n + idx] = this.store(value, direction);
          }
        }
      }
    }
  }

  snapshot(): Float64Array {
    return Float64Array.from(this.source);
  }

  private index(x: number, y: number, z: number): number {
    return x + this.nx * (y + this.ny * z);
  }

  private store(value: number, direction: number): number {
    return this.storage === 'shifted-fp16' ? shiftedFp16(value, direction) : value;
  }

  step(): StepMeasurement {
    const rho = new Float64Array(this.n);
    const velocity = new Float64Array(3 * this.n);
    const tau = new Float64Array(this.n);
    const pi = new Float64Array(this.n);
    const feq = new Float64Array(D3Q19.q);
    const tensor = new Float64Array(6);

    for (let z = 0; z < this.nz; z++) {
      for (let y = 0; y < this.ny; y++) {
        for (let x = 0; x < this.nx; x++) {
          const idx = this.index(x, y, z);
          for (let direction = 0; direction < D3Q19.q; direction++) {
            const sx = (x - D3Q19.ex[direction] + this.nx) % this.nx;
            const sy = (y - D3Q19.ey[direction] + this.ny) % this.ny;
            const sz = (z - D3Q19.ez[direction] + this.nz) % this.nz;
            this.gathered[direction] = this.source[direction * this.n + this.index(sx, sy, sz)];
          }

          let cellRho = 0;
          let ux = 0;
          let uy = 0;
          let uz = 0;
          for (let direction = 0; direction < D3Q19.q; direction++) {
            const value = this.gathered[direction];
            cellRho += value;
            ux += D3Q19.ex[direction] * value;
            uy += D3Q19.ey[direction] * value;
            uz += D3Q19.ez[direction] * value;
          }
          ux /= cellRho;
          uy /= cellRho;
          uz /= cellRho;
          rho[idx] = cellRho;
          velocity[3 * idx] = ux;
          velocity[3 * idx + 1] = uy;
          velocity[3 * idx + 2] = uz;
          for (let direction = 0; direction < D3Q19.q; direction++) {
            feq[direction] = equilibrium3(D3Q19_SPEC, direction, cellRho, ux, uy, uz);
          }
          piNeq(this.gathered, feq, D3Q19_SPEC, tensor);
          pi[idx] = tensor[this.target.index];

          collideCell(this.gathered, this.ctx);
          tau[idx] = this.ctx.macro[4];
          for (let direction = 0; direction < D3Q19.q; direction++) {
            this.destination[direction * this.n + idx] = this.store(
              this.gathered[direction],
              direction,
            );
          }
        }
      }
    }

    const hydroFd = new Float64Array(this.n);
    const hydroAnalytic = new Float64Array(this.n);
    const polarizedVelocity = new Float64Array(this.n);
    for (let idx = 0; idx < this.n; idx++) {
      polarizedVelocity[idx] = velocity[3 * idx + this.polarization];
    }
    const velocityHat = fourier(polarizedVelocity, this.coordinates, this.k);
    const derivativeHat = { re: -this.k * velocityHat.im, im: this.k * velocityHat.re };

    for (let z = 0; z < this.nz; z++) {
      for (let y = 0; y < this.ny; y++) {
        for (let x = 0; x < this.nx; x++) {
          const idx = this.index(x, y, z);
          const minus = [x, y, z];
          const plus = [x, y, z];
          const extent = this.waveAxis === 0 ? this.nx : this.waveAxis === 1 ? this.ny : this.nz;
          minus[this.waveAxis] = (minus[this.waveAxis] - 1 + extent) % extent;
          plus[this.waveAxis] = (plus[this.waveAxis] + 1) % extent;
          const minusIdx = this.index(minus[0], minus[1], minus[2]);
          const plusIdx = this.index(plus[0], plus[1], plus[2]);
          const fd =
            (velocity[3 * plusIdx + this.polarization] -
              velocity[3 * minusIdx + this.polarization]) /
            2;
          const angle = this.k * this.coordinates[idx];
          const analytic =
            2 * (derivativeHat.re * Math.cos(angle) - derivativeHat.im * Math.sin(angle));
          const factor = -rho[idx] * CS2 * tau[idx];
          hydroFd[idx] = factor * fd;
          hydroAnalytic[idx] = factor * analytic;
        }
      }
    }

    const previous = this.source;
    this.source = this.destination;
    this.destination = previous;
    this.stepNumber++;
    const piHat = fourier(pi, this.coordinates, this.k);
    const measurement: StepMeasurement = {
      step: this.stepNumber,
      tauMean: mean(Array.from(tau)),
      velocityModeAmplitude: 2 * magnitude(velocityHat),
      piModeAmplitude: 2 * magnitude(piHat),
      finiteDifference: ratioMeasurement(pi, hydroFd, this.coordinates, this.k),
      analyticDerivative: ratioMeasurement(pi, hydroAnalytic, this.coordinates, this.k),
    };
    if (this.previousHydroFd) {
      const midpoint = new Float64Array(this.n);
      for (let idx = 0; idx < this.n; idx++) {
        midpoint[idx] = 0.5 * (this.previousHydroFd[idx] + hydroFd[idx]);
      }
      measurement.previousStepFiniteDifference = ratioMeasurement(
        pi,
        this.previousHydroFd,
        this.coordinates,
        this.k,
      );
      measurement.midpointFiniteDifference = ratioMeasurement(
        pi,
        midpoint,
        this.coordinates,
        this.k,
      );
    }
    this.previousHydroFd = hydroFd;
    return measurement;
  }
}

function runCase(spec: WaveCase): CaseResult {
  const mode = spec.mode ?? 1;
  const steps = spec.steps ?? MAIN_STEPS;
  const discard = spec.discard ?? MAIN_DISCARD;
  const simulation = new PeriodicShearWave(spec);
  const samples: StepMeasurement[] = [];
  let nonFinite = false;
  for (let step = 0; step < steps; step++) {
    const measurement = simulation.step();
    nonFinite ||= !Number.isFinite(measurement.finiteDifference.real);
    if (step >= discard) samples.push(measurement);
  }
  if (samples.length === 0) throw new Error(`${spec.id}: no post-transient samples`);
  const first = samples[0];
  const last = samples[samples.length - 1];
  const elapsed = last.step - first.step;
  const decayRate =
    elapsed > 0
      ? -Math.log(last.velocityModeAmplitude / first.velocityModeAmplitude) / elapsed
      : Number.NaN;
  const previous = samples.flatMap((sample) =>
    sample.previousStepFiniteDifference ? [sample.previousStepFiniteDifference] : [],
  );
  const midpoint = samples.flatMap((sample) =>
    sample.midpointFiniteDifference ? [sample.midpointFiniteDifference] : [],
  );
  const k = simulation.k;
  return {
    id: spec.id,
    targetComponent: simulation.target.name,
    waveAxis: spec.waveAxis,
    polarization: spec.polarization,
    background: spec.background,
    mode,
    wavelength: LONG_AXIS / mode,
    wavenumber: k,
    centeredDifferenceTransfer: Math.sin(k) / k,
    storage: spec.storage ?? 'float64',
    collision: spec.collision ?? 'trt',
    regularize: spec.regularize ?? true,
    tau0: spec.tau ?? AHMED_TAU0,
    lesCs: spec.lesCs ?? AHMED_LES_CS,
    samples: samples.length,
    finiteDifference: meanRatio(samples.map((sample) => sample.finiteDifference)),
    analyticDerivative: meanRatio(samples.map((sample) => sample.analyticDerivative)),
    previousStepFiniteDifference: meanRatio(previous),
    midpointFiniteDifference: meanRatio(midpoint),
    decayRate,
    firstSample: first,
    lastSample: last,
    nonFinite,
    rawSamples: samples,
    finalState: simulation.snapshot(),
  };
}

function withoutState(result: CaseResult): Omit<CaseResult, 'finalState'> {
  const { finalState, ...serializable } = result;
  void finalState;
  return serializable;
}

function relativeDifference(a: number, b: number): number {
  return Math.abs(a - b) / Math.max(Math.abs(a), Math.abs(b));
}

function get(id: string): CaseResult {
  const result = results.get(id);
  if (!result) throw new Error(`missing calibration case ${id}`);
  return result;
}

