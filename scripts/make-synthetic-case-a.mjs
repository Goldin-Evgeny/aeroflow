/**
 * Generates the SYNTHETIC AIJ Case A placeholder fixture.
 *
 * This file contains NO AIJ data. It is an analytic stand-in with the same schema, so the
 * app builds, typechecks and tests without the real benchmark data present. Anything scored
 * against it is labelled SYNTHETIC and is never a verdict (CLAUDE.md rule 5).
 *
 * To score the real benchmark, follow docs/BENCHMARK-DATA.md: download the AIJ workbook and
 * run scripts/convert-aij-case-a.py, which overwrites this file with the measured fixture.
 *
 *   node scripts/make-synthetic-case-a.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(
  new URL('../apps/studio/src/sim/cases/data/aij-case-a.json', import.meta.url),
);

const B = 0.08; // building half-width, m — published geometry, not measured data
const H = 2 * B; // building height, m
const U_REF = 1.0; // synthetic reference speed, m/s
const ALPHA = 0.25; // power-law exponent

/** Approach profile: plain power law, clamped near the ground. */
const inflowU = (z) => U_REF * Math.pow(Math.max(z, 1e-3) / H, ALPHA);

/**
 * Crude analytic wake so the field is not uniform: a velocity deficit in a box behind the
 * building, tapering downstream. Purely illustrative — no physical claim.
 */
function velocity(xOverB, yOverB, zOverB) {
  const z = zOverB * B;
  const base = inflowU(z);
  const inWake = xOverB > 0.5 && xOverB < 6 && Math.abs(yOverB) < 1.2 && zOverB < 2.2;
  const deficit = inWake ? 0.55 * Math.exp(-(xOverB - 0.5) / 3) : 0;
  const U = base * (1 - deficit);
  const V = inWake ? 0.05 * base * Math.sign(yOverB || 1) : 0;
  const W = inWake ? 0.04 * base : 0;
  return { U, V, W };
}

const round = (v) => Number(v.toFixed(6));

const inflow = Array.from({ length: 24 }, (_, i) => {
  const zOverB = 0.0625 + i * 0.25;
  const U = inflowU(zOverB * B);
  return { zOverB: round(zOverB), U: round(U), sigmaU: round(0.12 * U), k: round(0.02 * U * U) };
});

function plane(name, coords) {
  return {
    name,
    points: coords.map(([xOverB, yOverB, zOverB], i) => {
      const { U, V, W } = velocity(xOverB, yOverB, zOverB);
      return {
        i: i + 1,
        xOverB: round(xOverB),
        yOverB: round(yOverB),
        zOverB: round(zOverB),
        U: round(U),
        V: round(V),
        W: round(W),
      };
    }),
  };
}

// Vertical centre-plane (y = 0): 11 streamwise stations x 6 heights = 66 points.
const verticalCoords = [];
for (let xi = 0; xi < 11; xi++) {
  for (let zi = 0; zi < 6; zi++) {
    verticalCoords.push([-2 + xi * 0.8, 0, 0.125 + zi * 0.5]);
  }
}

// Horizontal planes: 12 streamwise stations x 5 lateral offsets = 60 points each.
function horizontalCoords(zOverB) {
  const out = [];
  for (let xi = 0; xi < 12; xi++) {
    for (let yi = 0; yi < 5; yi++) {
      out.push([-2 + xi * 0.8, -2 + yi * 1.0, zOverB]);
    }
  }
  return out;
}

const fixture = {
  source:
    'SYNTHETIC placeholder — contains NO AIJ data. Analytic stand-in generated by ' +
    'scripts/make-synthetic-case-a.mjs so the project builds and tests without the ' +
    'benchmark data present. Any score against it is labelled SYNTHETIC and is not a ' +
    'verdict. See docs/BENCHMARK-DATA.md to obtain the real AIJ Case A fixture.',
  synthetic: true,
  units: {
    length: 'multiples of b (multiply by bMeters for model-scale meters)',
    velocity: 'm/s, synthetic (NOT normalized)',
    k: 'm2/s2',
  },
  coordinates:
    'Data convention: origin at the building center on the ground, x streamwise ' +
    '(+x downstream), y lateral, z vertical (up).',
  bMeters: B,
  buildingHeightMeters: H,
  uRefMps: U_REF,
  uRef: `${U_REF} m/s — synthetic reference speed, chosen so normalized values are O(1).`,
  notes:
    'Generated, not measured. The wake is a crude exponential deficit with no physical ' +
    'claim; it exists only so the field is non-uniform and the scoring pipeline exercises ' +
    'realistic code paths.',
  inflow,
  planes: [
    plane('vertical-centerplane', verticalCoords),
    plane('horizontal-0.125b', horizontalCoords(0.125)),
    plane('horizontal-1.25b', horizontalCoords(1.25)),
  ],
};

writeFileSync(OUT, JSON.stringify(fixture, null, 2) + '\n');
console.log(
  `wrote SYNTHETIC ${OUT}\n  inflow ${inflow.length} pts, planes: ` +
    fixture.planes.map((p) => `${p.name}:${p.points.length}`).join(' '),
);
